import type { Dir } from '$engine/grid';
import type { Action } from '$engine/types';
import type { BasicActionId, InventionDef, MemberId, ScenarioDef } from './types';

const cast = (unit: MemberId, dir: 'right' | 'down' = 'right'): Action => ({
  type: 'cast',
  unit,
  spell: '0,0',
  aim: { kind: 'dir', dir },
});
const at = (unit: MemberId, x: number, y: number): Action => ({
  type: 'cast',
  unit,
  spell: '0,0',
  aim: { kind: 'tile', at: { x, y } },
});
const basic = (type: BasicActionId, unit: MemberId, dir: Dir): Action =>
  ({ type, unit, dir }) as Action;
const move = (unit: MemberId, x: number, y: number): Action => ({
  type: 'move',
  unit,
  to: { x, y },
});
